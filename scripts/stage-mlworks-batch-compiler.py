#!/usr/bin/env python3
"""Stage the compiler for bounded MLWorks object compilation (no remote actions).

Portable source is generated by sml-target. This bootstrap layer adds MLWorks
build directives, chooses a coherent Basis and defers the CLI until image entry.
"""
import argparse
from pathlib import Path
import re
import shutil
import subprocess
from mlworks_project import project_text

repo = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('output', type=Path)
parser.add_argument('--library-path', default='/home/ellie/testingstuff/mlworks-r5900/target-objects')
parser.add_argument('--memory-wrapper', type=Path,
                    default=repo.parent / 'mlworks/tools/scripts/run-memory-limited.sh')
args = parser.parse_args()
if '\n' in args.library_path or '\r' in args.library_path:
    parser.error('library path must occupy one project-file line')
if not args.memory_wrapper.is_file():
    parser.error('supply --memory-wrapper with the MLWorks allocation/watchdog wrapper')
out = args.output.resolve()
subprocess.run(['python3', repo / 'scripts/stage-sml-compiler.py', 'mlworks', out], check=True)
loader = (out / 'load.sml').read_text()
names = re.findall(r'"([a-z_0-9]+\.sml)"', loader)
if not names or names[0] != 'prelude.sml' or names[-1] != 'main.sml':
    raise SystemExit('unexpected SML target loader order')
for name in names:
    path = out / name
    text = path.read_text()
    imports = ['require_all']
    if name != 'prelude.sml':
        imports.append('prelude')
        original = (repo / 'src' / name).read_text()
        imports.extend(Path(unit).stem for unit in re.findall(
            r'from "([^"\n]+\.sml)" import \* as [A-Za-z_0-9]+;', original))
        if name == 'subset_host.sml':
            imports.append('subset_result')
    if name == 'main.sml':
        marker = 'val _ = Main.main ()'
        if not text.rstrip().endswith(marker):
            raise SystemExit('unexpected compiler CLI startup declaration')
        text = text.rstrip()[:-len(marker)]
    imports = list(dict.fromkeys(imports))
    path.write_text(''.join('require "' + unit + '";\n' for unit in imports) + text)
(out / 'compiler.mlp').write_text(project_text('compiler.mlp', names, 'main.sml', args.library_path))
(out / 'units.txt').write_text('\n'.join(Path(name).stem for name in names) + '\n')
shutil.copyfile(args.memory_wrapper, out / 'run-memory-limited.sh')
shutil.copyfile(repo / 'lib/mlworks/run-subsetml.sh', out / 'run-subsetml.sh')
print(out)
