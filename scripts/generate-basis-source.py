"""Embed the authoritative Option declaration for the legacy host compatibility checker."""
from pathlib import Path

repository = Path(__file__).resolve().parents[1]
source = (repository / "src/subset_option_value.sml").read_bytes()
literal = '"' + ''.join(
    chr(byte) if 32 <= byte <= 126 and byte not in (34, 92) else f"\\{byte:03d}"
    for byte in source
) + '"'
output = repository / "src/basis_source.sml"
text = ("(* Generated by scripts/generate-basis-source.py from subset_option_value.sml. *)\n"
        "structure BasisSource = struct\n"
        f"  val option = {literal}\n"
        "end\n")
if not output.exists() or output.read_text() != text:
    output.write_text(text)
